"""Builds site/console/index.html: the real consulting/console.html plus a shim that answers its two API
calls in the browser with site/console/model.js, so the workspace runs on GitHub Pages without a server.

Run after changing consulting/console.html or data/: python scripts/build_console_site.py
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def render() -> str:
    console = (ROOT / "consulting/console.html").read_text()
    scenarios = json.loads((ROOT / "data/scenarios.json").read_text())
    with (ROOT / "data/use-cases.csv").open(newline="") as file:
        use_cases = list(csv.DictReader(file))
    shim = f"""<script type="module">
// Static-hosting shim: answers /api/scenarios and /api/calculate in the browser with model.js, a tested
// port of consulting/business_case.py. Generated by scripts/build_console_site.py; do not edit by hand.
import {{ calculate, prioritize, ScenarioError }} from './model.js';
const SCENARIOS = {json.dumps(scenarios)};
const USE_CASES = {json.dumps(use_cases, ensure_ascii=False)};
const reply = (status, body) => new Response(JSON.stringify(body), {{ status, headers: {{ 'Content-Type': 'application/json' }} }});
const realFetch = window.fetch.bind(window);
window.fetch = async (url, init = {{}}) => {{
  const path = new URL(url, location.href).pathname;
  if (path.endsWith('/api/scenarios')) return reply(200, {{ scenarios: SCENARIOS, prioritization: prioritize(USE_CASES) }});
  if (path.endsWith('/api/calculate')) {{
    try {{ return reply(200, calculate(JSON.parse(init.body))); }}
    catch (e) {{ if (e instanceof ScenarioError || e instanceof SyntaxError) return reply(422, {{ detail: 'Check all numeric assumptions and rates; rates must be 0..1' }}); throw e; }}
  }}
  return realFetch(url, init);
}};
window.dispatchEvent(new Event('shim-ready'));
</script>
"""
    head, body = console.split("<body>", 1)
    # The console's own script runs as soon as it is parsed, so it waits until the module shim is ready.
    body = body.replace("<script>\n(()=>{", "<script>\nwindow.addEventListener('shim-ready',()=>{", 1)
    assert "window.addEventListener('shim-ready'" in body, "console script start not found"
    assert body.count("})();\n</script>") == 1, "console script end not found"
    body = body.replace("})();\n</script>", "});\n</script>", 1)
    banner = ('<div style="background:#fff7e0;color:#5b4400;padding:8px 36px;font:13px/1.5 system-ui">'
              'Static copy on GitHub Pages: calculations run in your browser with a tested port of the Python model. '
              '<a href="../">Back to the showcase</a></div>')
    return head + shim + "<body>" + banner + body


if __name__ == "__main__":
    (ROOT / "site/console").mkdir(parents=True, exist_ok=True)
    (ROOT / "site/console/index.html").write_text(render())
    print("wrote site/console/index.html")
